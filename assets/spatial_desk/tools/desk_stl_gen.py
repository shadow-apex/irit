_REPO_ROOT = os.path.abspath(os.path.join(_HERE, "..", "..", ".."))
_CORE_TOOLS_DIR = os.path.join(_REPO_ROOT, "tools")
if _CORE_TOOLS_DIR not in sys.path:
    sys.path.insert(0, _CORE_TOOLS_DIR)

