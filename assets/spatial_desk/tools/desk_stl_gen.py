"""
assets/spatial_desk/tools/desk_stl_gen.py — AI Thiết kế & Bộ sinh file in 3D (.STL) qua OpenSCAD tham số.

Kế thừa kiến trúc AgentSCAD (YTUONG.MD mục 1.6):
1. Nhận kích thước đo từ mặt bàn (`length_mm`, `width_mm`, `height_mm`, `wall_mm`, `clearance_mm`).
2. Sinh mã nguồn CAD tham số chuẩn OpenSCAD (`.scad`).
3. Biên dịch ra file in 3D `.STL` kín nước (watertight mesh) trực tiếp ra Desktop (ưu tiên gọi OpenSCAD CLI nếu có, kèm bộ dựng lưới tam giác 3D nội sinh đảm bảo hoạt động 100% độc lập).
4. Xuất dữ liệu lưới 3D (`preview_mesh`) để máy chiếu chiếu mô hình 3D xoay 360 độ ngay trên mặt bàn.
"""
import math
import os
