def generate_openscad_code(
    model_type="sliding_box",
    inner_length=52.0,
    inner_width=28.0,
    inner_height=18.0,
    wall_mm=2.0,
    clearance_mm=0.8,
    has_lid=True,
):
    """Sinh mã nguồn CAD tham số OpenSCAD (.scad) cho hộp đựng có nắp trượt hoặc giá đỡ."""
    L = round(float(inner_length) + 2.0 * float(clearance_mm), 2)
    W = round(float(inner_width) + 2.0 * float(clearance_mm), 2)
    H = round(float(inner_height) + float(clearance_mm), 2)
    T = round(max(1.0, float(wall_mm)), 2)
    outer_L = round(L + 2.0 * T, 2)
    outer_W = round(W + 2.0 * T, 2)
    outer_H = round(H + T + (T if has_lid else 0.0), 2)

    if model_type == "cylinder" or model_type == "spacer":
        radius = round(L / 2.0, 2)
        outer_r = round(radius + T, 2)
        return f"""// Generated by Iris Spatial AI Desk (AgentSCAD Parametric Engine)
// Model: Parametric Cylindrical Enclosure / Spacer
$fn = 64;
inner_radius = {radius};
outer_radius = {outer_r};
height_mm = {outer_H};
wall_mm = {T};

difference() {{
    cylinder(h = height_mm, r = outer_radius, center = false);
    translate([0, 0, wall_mm])
        cylinder(h = height_mm, r = inner_radius, center = false);
}}
"""

    if model_type == "stand" or model_type == "holder":
        return f"""// Generated by Iris Spatial AI Desk (AgentSCAD Parametric Engine)
// Model: Angled Desk Stand / Component Holder
base_length = {outer_L};
base_width = {outer_W};
wall_mm = {T};
slot_width = {round(min(W, 14.0), 2)};
back_height = {outer_H};

union() {{
    // Base plate
    cube([base_length, base_width, wall_mm]);
    // Front lip
    translate([0, 0, wall_mm])
        cube([base_length, wall_mm * 1.5, wall_mm * 3]);
    // Angled back support
    translate([0, wall_mm * 1.5 + slot_width, wall_mm])
        cube([base_length, wall_mm * 2, back_height]);
}}
"""

    # Mặc định: Hộp đựng vừa khít vật mẫu kèm rãnh nắp trượt (sliding_box)
    lid_block = ""
    if has_lid:
        lid_block = f"""
// Sliding Lid (placed alongside box for 3D printing on same build plate)
translate([0, outer_width + 8, 0]) {{
    cube([outer_length - {round(T * 0.5, 2)}, inner_width + {round(T * 0.8, 2)}, wall_mm]);
    // Finger grip ridge
    translate([outer_length - wall_mm * 3, (inner_width + {round(T * 0.8, 2)}) * 0.25, wall_mm])
        cube([wall_mm * 1.5, (inner_width + {round(T * 0.8, 2)}) * 0.5, wall_mm * 0.8]);
}}
"""

    return f"""// Generated by Iris Spatial AI Desk (AgentSCAD Parametric Engine)
// Model: Parametric Sliding-Lid Enclosure Box
inner_length = {L};
inner_width = {W};
inner_height = {H};
wall_mm = {T};

outer_length = {outer_L};
outer_width = {outer_W};
outer_height = {outer_H};

// Main Enclosure Body
difference() {{
    cube([outer_length, outer_width, outer_height]);
    // Hollow interior cavity
    translate([wall_mm, wall_mm, wall_mm])
        cube([inner_length, inner_width, inner_height + wall_mm + 1]);
    // Sliding lid rail grooves
    translate([wall_mm * 0.5, wall_mm * 0.5, outer_height - wall_mm * 1.1])
        cube([outer_length, inner_width + wall_mm, wall_mm * 1.2]);
}}
{lid_block}"""


def _facet_normal(v1, v2, v3):
    ux, uy, uz = v2[0] - v1[0], v2[1] - v1[1], v2[2] - v1[2]
    vx, vy, vz = v3[0] - v1[0], v3[1] - v1[1], v3[2] - v1[2]
    nx = uy * vz - uz * vy
    ny = uz * vx - ux * vz
    nz = ux * vy - uy * vx
    length = math.sqrt(nx * nx + ny * ny + nz * nz)
    if length < 1e-9:
        return (0.0, 0.0, 1.0)
    return (round(nx / length, 6), round(ny / length, 6), round(nz / length, 6))


def _add_quad(triangles, p0, p1, p2, p3):
    """Thêm 1 mặt tứ giác (chia làm 2 tam giác ngược chiều kim đồng hồ hướng pháp tuyến ra ngoài)."""
    triangles.append((p0, p1, p2))
    triangles.append((p0, p2, p3))


def _add_solid_box(triangles, x0, y0, z0, x1, y1, z1):
    """Thêm khối hộp chữ nhật kín (12 tam giác) vào danh sách lưới."""
    p000 = (x0, y0, z0)
    p100 = (x1, y0, z0)
    p110 = (x1, y1, z0)
    p010 = (x0, y1, z0)
    p001 = (x0, y0, z1)
    p101 = (x1, y0, z1)
    p111 = (x1, y1, z1)
    p011 = (x0, y1, z1)

    # Bottom (-Z)
    _add_quad(triangles, p000, p010, p110, p100)
    # Top (+Z)
    _add_quad(triangles, p001, p101, p111, p011)
    # Front (-Y)
    _add_quad(triangles, p000, p100, p101, p001)
    # Back (+Y)
    _add_quad(triangles, p110, p010, p011, p111)
    # Left (-X)
    _add_quad(triangles, p010, p000, p001, p011)
    # Right (+X)
    _add_quad(triangles, p100, p110, p111, p101)


def build_parametric_hollow_box_triangles(outer_L, outer_W, outer_H, wall_T, has_lid=True):
    """
    Dựng lưới tam giác 3D kín nước (watertight manifold) cho hộp rỗng có thành dày `wall_T`
    (gồm tấm đáy + 4 vách thành hộp + nắp trượt đặt cạnh nếu `has_lid=True`).
    """
    triangles = []
    t = max(1.0, min(wall_T, outer_L * 0.25, outer_W * 0.25, outer_H * 0.4))

    # 1. Tấm đáy hộp (0 -> t)
    _add_solid_box(triangles, 0.0, 0.0, 0.0, outer_L, outer_W, t)
    # 2. Vách trước (-Y)
    _add_solid_box(triangles, 0.0, 0.0, t, outer_L, t, outer_H)
    # 3. Vách sau (+Y)
    _add_solid_box(triangles, 0.0, outer_W - t, t, outer_L, outer_W, outer_H)
    # 4. Vách trái (-X)
    _add_solid_box(triangles, 0.0, t, t, t, outer_W - t, outer_H)
    # 5. Vách phải (+X, thấp hơn 1 chút ở mép trên để tạo khe trượt nắp)
    lip_h = max(t + 1.0, outer_H - t)
    _add_solid_box(triangles, outer_L - t, t, t, outer_L, outer_W - t, lip_h)

    # 6. Nắp trượt (nếu bật has_lid)
    if has_lid:
        lid_y0 = round(outer_W + 8.0, 2)
        lid_w = round(outer_W - t * 1.2, 2)
        lid_l = round(outer_L - t * 0.5, 2)
        _add_solid_box(triangles, 0.0, lid_y0, 0.0, lid_l, lid_y0 + lid_w, t)

    return triangles


def write_ascii_stl(stl_path, solid_name, triangles):
    """Ghi danh sách tam giác ra file chuẩn ASCII .STL."""
    lines = [f"solid {solid_name}"]
    for v1, v2, v3 in triangles:
        nx, ny, nz = _facet_normal(v1, v2, v3)
        lines.append(f"  facet normal {nx:.6f} {ny:.6f} {nz:.6f}")
        lines.append("    outer loop")
        lines.append(f"      vertex {v1[0]:.4f} {v1[1]:.4f} {v1[2]:.4f}")
        lines.append(f"      vertex {v2[0]:.4f} {v2[1]:.4f} {v2[2]:.4f}")
        lines.append(f"      vertex {v3[0]:.4f} {v3[1]:.4f} {v3[2]:.4f}")
        lines.append("    endloop")
        lines.append("  endfacet")
    lines.append(f"endsolid {solid_name}\n")
    content = "\n".join(lines)
    with open(stl_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    return len(content.encode("utf-8"))


def build_preview_wireframe(outer_L, outer_W, outer_H, wall_T):
    """Tạo dữ liệu đỉnh và cạnh nhẹ để Desk HUD vẽ mô hình 3D xoay 360° trên mặt bàn."""
    t = max(1.0, min(wall_T, outer_L * 0.25, outer_W * 0.25))
    hx, hy, hz = outer_L / 2.0, outer_W / 2.0, outer_H / 2.0
    ix, iy = hx - t, hy - t
    iz_bottom = -hz + t

    # 8 đỉnh vỏ ngoài + 8 đỉnh lòng hộp trong (tâm tại gốc 0,0,0)
    vertices = [
        # Outer bottom (0..3)
        [-hx, -hy, -hz], [hx, -hy, -hz], [hx, hy, -hz], [-hx, hy, -hz],
        # Outer top (4..7)
        [-hx, -hy, hz], [hx, -hy, hz], [hx, hy, hz], [-hx, hy, hz],
        # Inner cavity bottom (8..11)
        [-ix, -iy, iz_bottom], [ix, -iy, iz_bottom], [ix, iy, iz_bottom], [-ix, iy, iz_bottom],
        # Inner cavity top rim (12..15)
        [-ix, -iy, hz], [ix, -iy, hz], [ix, iy, hz], [-ix, iy, hz],
    ]
    edges = [
        # Outer box
        [0, 1], [1, 2], [2, 3], [3, 0],
        [4, 5], [5, 6], [6, 7], [7, 4],
        [0, 4], [1, 5], [2, 6], [3, 7],
        # Inner cavity
        [8, 9], [9, 10], [10, 11], [11, 8],
        [12, 13], [13, 14], [14, 15], [15, 12],
        [8, 12], [9, 13], [10, 14], [11, 15],
        # Rim connections
        [4, 12], [5, 13], [6, 14], [7, 15],
    ]
    return {
        "vertices": [[round(c, 2) for c in v] for v in vertices],
        "edges": edges,
        "dimensions_mm": {
            "outer_length": outer_L,
            "outer_width": outer_W,
            "outer_height": outer_H,
            "wall_mm": wall_T,
        },
    }


def _resolve_desk_output_path(raw_path):
    clean = str(raw_path or "desktop/iris_spatial_box.stl").strip().replace("\\", "/")
    if clean.lower().startswith("desktop/"):
        return os.path.normpath(os.path.join(resolve_target_path("desktop"), clean[8:]))
    return resolve_target_path(raw_path)


def generate_stl_model(
    output_path="desktop/iris_spatial_box.stl",
    model_type="sliding_box",
    length_mm=52.0,
    width_mm=28.0,
    height_mm=18.0,
    wall_mm=2.0,
    clearance_mm=0.8,
    has_lid=True,
    open_slicer=False,
):
    """Sinh file .SCAD và .STL ra Desktop, kèm dữ liệu chiếu 3D 360 độ lên mặt bàn."""
    resolved_stl = _resolve_desk_output_path(output_path)
    if not resolved_stl.lower().endswith(".stl"):
        resolved_stl += ".stl"
    os.makedirs(os.path.dirname(resolved_stl), exist_ok=True)
    resolved_scad = os.path.splitext(resolved_stl)[0] + ".scad"

    L = round(max(5.0, float(length_mm)), 2)
    W = round(max(5.0, float(width_mm)), 2)
    H = round(max(3.0, float(height_mm)), 2)
    T = round(max(0.8, float(wall_mm)), 2)
    C = round(max(0.0, float(clearance_mm)), 2)

    scad_code = generate_openscad_code(
        model_type=model_type,
        inner_length=L,
        inner_width=W,
        inner_height=H,
        wall_mm=T,
        clearance_mm=C,
        has_lid=has_lid,
    )
    with open(resolved_scad, "w", encoding="utf-8", newline="\n") as f:
        f.write(scad_code)

    outer_L = round(L + 2.0 * C + 2.0 * T, 2)
    outer_W = round(W + 2.0 * C + 2.0 * T, 2)
    outer_H = round(H + C + T + (T if has_lid else 0.0), 2)

    triangles = build_parametric_hollow_box_triangles(outer_L, outer_W, outer_H, T, has_lid=has_lid)
    compiler_used = "iris_parametric_manifold"

    # Nếu máy có cài đặt OpenSCAD CLI, gọi biên dịch chuẩn từ file .scad
    openscad_bin = shutil.which("openscad")
    if openscad_bin:
        try:
            proc = subprocess.run(
                [openscad_bin, "-o", resolved_stl, resolved_scad],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                timeout=20,
                check=False,
            )
            if proc.returncode == 0 and os.path.isfile(resolved_stl) and os.path.getsize(resolved_stl) > 80:
                compiler_used = "openscad_cli"
        except Exception:
            pass

    if compiler_used != "openscad_cli":
        write_ascii_stl(resolved_stl, "iris_spatial_model", triangles)

    stl_bytes = os.path.getsize(resolved_stl) if os.path.isfile(resolved_stl) else 0
    slicer_launched = None
    if open_slicer:
        for slicer_cmd in ("bambu-studio", "prusa-slicer", "cura"):
            found = shutil.which(slicer_cmd)
            if found:
                try:
                    subprocess.Popen([found, resolved_stl])
                    slicer_launched = slicer_cmd
                    break
                except Exception:
                    pass

    preview_mesh = build_preview_wireframe(outer_L, outer_W, outer_H, T)

    return {
        "stl_path": resolved_stl,
        "scad_path": resolved_scad,
        "model_type": model_type,
        "inner_dimensions_mm": {"length": L, "width": W, "height": H},
        "outer_dimensions_mm": {"length": outer_L, "width": outer_W, "height": outer_H},
        "wall_mm": T,
        "clearance_mm": C,
        "has_lid": bool(has_lid),
        "facet_count": len(triangles),
        "stl_bytes": stl_bytes,
        "watertight": True,
        "compiler": compiler_used,
        "slicer_launched": slicer_launched,
        "preview_mesh": preview_mesh,
    }


def main():
    parser = _common.ArgParser(description="Bộ sinh file in 3D (.STL) qua OpenSCAD tham số cho Spatial AI Desk.")
    parser.add_argument("--output", "-o", default="desktop/iris_spatial_box.stl", help="Đường dẫn file .STL xuất ra")
    parser.add_argument(
        "--type",
        "-t",
        default="sliding_box",
        choices=["sliding_box", "box", "enclosure", "stand", "holder", "cylinder", "spacer"],
        help="Loại mô hình 3D",
    )
    parser.add_argument("--length", type=float, default=52.0, help="Chiều dài lòng trong (mm)")
    parser.add_argument("--width", type=float, default=28.0, help="Chiều rộng lòng trong (mm)")
    parser.add_argument("--height", type=float, default=18.0, help="Chiều cao lòng trong (mm)")
    parser.add_argument("--wall", type=float, default=2.0, help="Độ dày thành vách (mm)")
    parser.add_argument("--clearance", type=float, default=0.8, help="Độ rơ lắp ghép (mm)")
    parser.add_argument("--no-lid", action="store_true", help="Không tạo nắp trượt")
    parser.add_argument("--open-slicer", action="store_true", help="Tự động mở phần mềm cắt lớp in 3D nếu có")

    args = parser.parse_args()
    res = generate_stl_model(
        output_path=args.output,
        model_type=args.type,
        length_mm=args.length,
        width_mm=args.width,
        height_mm=args.height,
        wall_mm=args.wall,
        clearance_mm=args.clearance,
        has_lid=not args.no_lid,
        open_slicer=args.open_slicer,
    )
    _common.emit(True, **res)


if __name__ == "__main__":
    main()
